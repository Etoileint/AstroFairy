class LockError(RuntimeError):
    pass


@dataclass(frozen=True)
class Pin:
    name: str
    version: str
    marker: str | None
    hashes: tuple[str, ...]


@dataclass(frozen=True)
class Profile:
    name: str
    roots: Path
    lock: Path
    snapshots: Path


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=".lock-")
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        Path(temporary).chmod(0o644)
        Path(temporary).replace(path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def _read_config(root: Path) -> dict[str, Any]:
    path = root / CONFIG
    try:
        config = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise LockError(f"Unable to read {CONFIG.as_posix()}: {exc}") from exc
    if config.get("format") != 1:
        raise LockError("Unsupported dependency profile configuration format")
    policy = config.get("policy")
    if not isinstance(policy, dict):
        raise LockError("Dependency policy is missing")
    return config


def _profiles(config: dict[str, Any]) -> list[Profile]:
    result = []
    for item in config.get("profile", []):
        if not isinstance(item, dict) or set(item) != {"name", "roots", "lock", "snapshots"}:
            raise LockError("A dependency profile has an unexpected shape")
        profile = Profile(
            name=str(item["name"]),
            roots=Path(item["roots"]),
            lock=Path(item["lock"]),
            snapshots=Path(item["snapshots"]),
        )
        if not _NAME.fullmatch(profile.name):
            raise LockError(f"Invalid profile name: {profile.name}")
        for path in (profile.roots, profile.lock, profile.snapshots):
            if path.is_absolute() or ".." in path.parts:
                raise LockError(f"Profile paths must stay inside the repository: {path}")
        result.append(profile)
    if not result:
        raise LockError("At least one dependency profile is required")
    if len({item.name for item in result}) != len(result):
        raise LockError("Dependency profile names must be unique")
    return result


def _requires_python(root: Path, policy: dict[str, Any]) -> str:
    source = root / str(policy["python_from"])
    try:
        project = tomllib.loads(source.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise LockError(f"Unable to read project metadata: {exc}") from exc
    requires = project.get("project", {}).get("requires-python")
    if not isinstance(requires, str):
        raise LockError("Project metadata does not declare requires-python")
    try:
        specifier = SpecifierSet(requires)
    except InvalidSpecifier as exc:
        raise LockError(f"Invalid requires-python: {requires}") from exc
    bounds = [item for item in specifier if item.operator in {">=", ">"}]
    if not bounds:
        raise LockError("requires-python must declare a >= MAJOR.MINOR lower bound")
    bound = max(bounds, key=lambda item: Version(item.version))
    version = bound.version
    if not re.fullmatch(r"\d+\.\d+(?:\.\d+)?", version):
        raise LockError(f"Unsupported requires-python lower bound: {version}")
    return ".".join(version.split(".")[:2])


def _core_roots(root: Path) -> dict[str, Any]:
    source = root / "pyproject.toml"
    try:
        project = tomllib.loads(source.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise LockError(f"Unable to read project metadata: {exc}") from exc
    dependencies = project.get("project", {}).get("dependencies")
    if not isinstance(dependencies, list) or not dependencies:
        raise LockError("Project metadata declares no runtime dependencies")
    return {"kind": "project", "requirements": list(dependencies)}


def _file_roots(root: Path, profile: Profile) -> dict[str, Any]:
    try:
        text = (root / profile.roots).read_text(encoding="utf-8")
    except OSError as exc:
        raise LockError(f"Unable to read {profile.roots.as_posix()}: {exc}") from exc
    requirements = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            requirements.append(stripped)
    if not requirements:
        raise LockError(f"{profile.roots.as_posix()} declares no requirements")
    return {"kind": "file", "requirements": requirements}


def _roots(root: Path, profile: Profile) -> dict[str, Any]:
    return _core_roots(root) if profile.roots.name == "pyproject.toml" else _file_roots(root, profile)


def _root_inputs(root: Path, profile: Profile) -> tuple[list[str], str]:
    data = _roots(root, profile)
    policy = _read_config(root)["policy"]
    python = _requires_python(root, policy)
    requirements = []
    for item in data["requirements"]:
        try:
            requirement = Requirement(item)
        except InvalidRequirement as exc:
            raise LockError(f"Invalid root requirement {item!r}: {exc}") from exc
        if requirement.marker is not None or requirement.extras or requirement.url is not None:
            raise LockError(f"Root requirements must be exact pins without markers or extras: {item}")
        specifiers = list(requirement.specifier)
        if len(specifiers) != 1 or specifiers[0].operator != "==" or "*" in specifiers[0].version:
            raise LockError(f"Root requirements must use one exact pin: {item}")
        requirements.append(f"{canonicalize_name(requirement.name)}=={specifiers[0].version}")
    return sorted(requirements), python


def _input_digest(root: Path, profile: Profile) -> str:
    roots, python = _root_inputs(root, profile)
    body = {"format": 1, "profile": profile.name, "python": python, "roots": roots}
    return _digest(json.dumps(body, sort_keys=True, separators=(",", ":")).encode("utf-8"))


def _policy_digest(root: Path) -> str:
    config = _read_config(root)
    policy = {
        "index_url": config["policy"]["index_url"],
        "only_binary": config["policy"]["only_binary"],
        "python_versions": config["policy"]["python_versions"],
        "platforms": config["policy"]["platforms"],
        "machines": config["policy"]["machines"],
    }
    return _digest(json.dumps(policy, sort_keys=True, separators=(",", ":")).encode("utf-8"))


def _dev_tool_pin(root: Path, name: str, filename: str) -> str:
    try:
        text = (root / filename).read_text(encoding="utf-8")
    except OSError as exc:
        raise LockError(f"Unable to read the development tool lock: {exc}") from exc
    wanted = canonicalize_name(name)
    found = None
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        try:
            requirement = Requirement(stripped)
        except InvalidRequirement as exc:
            raise LockError(f"Invalid development tool pin: {stripped!r}") from exc
        if canonicalize_name(requirement.name) == wanted:
            versions = list(requirement.specifier)
            if len(versions) != 1 or versions[0].operator != "==":
                raise LockError(f"Development tool {name} must be pinned exactly")
            if found is not None and found != versions[0].version:
                raise LockError(f"Development tool {name} is pinned twice")
            found = versions[0].version
    if found is None:
        raise LockError(f"Development tool {name} is not pinned in {filename}")
    return found


def _uv_command(root: Path) -> list[str]:
    config = _read_config(root)
    pin = _dev_tool_pin(root, str(config["policy"]["uv_pin_name"]), str(config["policy"]["uv_pin_file"]))
    # Isolated mode removes PYTHONPATH/CWD module injection from tool identity probing.
    candidates: list[list[str]] = [[sys.executable, "-I", "-m", "uv"]]
    found = shutil.which("uv", path=_uv_environment().get("PATH"))
    if found is not None:
        candidates.append([found])
    environment = _uv_environment()
    for command in candidates:
        try:
            completed = subprocess.run(
                [*command, "--version"],
                capture_output=True,
                text=True,
                check=False,
                timeout=30,
                env=environment,
                cwd=root,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        fields = completed.stdout.split()
        if completed.returncode == 0 and len(fields) >= 2 and fields[1] == pin:
            return command
    raise LockError(f"No uv {pin} executable is available; install the pinned development tool")


def _uv_environment() -> dict[str, str]:
    return {key: value for key, value in os.environ.items() if key in _ENV_ALLOWLIST}


def _source_url(name: str, version: str) -> str:
    return f"https://pypi.org/pypi/{quote(name)}/{quote(version)}/json"


def _validate_source_url(url: str, name: str, version: str) -> None:
    parsed = urlsplit(url)
    if (
        parsed.scheme != "https"
        or parsed.hostname != _OFFICIAL_HOST
        or parsed.username is not None
        or parsed.password is not None
        or parsed.port not in {None, 443}
        or parsed.query
        or parsed.fragment
    ):
        raise LockError(f"Source URL is not the official PyPI metadata endpoint: {url[:120]}")
    parts = parsed.path.strip("/").split("/")
    if (
        len(parts) != 4
        or parts[0] != "pypi"
        or parts[3] != "json"
        or canonicalize_name(unquote(parts[1])) != canonicalize_name(name)
        or unquote(parts[2]) != version
    ):
        raise LockError(f"Source URL identity does not match {name}=={version}: {url[:120]}")


def _uv_executable(command: list[str]) -> Path:
    if not command:
        raise LockError("The selected uv command is empty")
    if len(command) >= 4 and command[1:4] == ["-I", "-m", "uv"]:
        completed = subprocess.run(
            [command[0], "-I", "-c", "import uv; print(uv.find_uv_bin())"],
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
            env=_uv_environment(),
        )
        path = completed.stdout.strip()
        if completed.returncode != 0 or not path:
            raise LockError("The isolated uv module cannot resolve its executable; install the pinned tool")
        candidate = Path(path)
    else:
        candidate = Path(command[0])
    if not candidate.is_file():
        raise LockError(f"The selected uv executable is not a readable file: {candidate}")
    return candidate


def _uv_executable_digest(command: list[str]) -> str:
    try:
        return _digest(_uv_executable(command).read_bytes())
    except OSError as exc:
        raise LockError("The selected uv executable cannot be read") from exc


def _parse_lock(text: str) -> list[Pin]:
    logical: list[str] = []
    buffer: list[str] = []
    for number, raw in enumerate(text.splitlines(), 1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            if buffer:
                raise LockError(f"Lock line {number}: unexpected break inside an entry")
            continue
        continued = stripped.endswith("\\")
        buffer.append(stripped[:-1].strip() if continued else stripped)
        if not continued:
            logical.append(" ".join(buffer))
            buffer = []
    if buffer:
        raise LockError("Lock ends with an unfinished entry")
    pins = []
    for entry in logical:
        head, *hash_fields = entry.split(" ")
        if not hash_fields:
            raise LockError(f"Lock entry has no hashes: {head}")
        requirement_text = entry.split(" --hash=")[0]
        match = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;]+)(?:\s*;\s*(.+))?", requirement_text)
        if match is None:
            raise LockError(f"Unsupported lock entry syntax: {entry[:80]}")
        name = canonicalize_name(match.group(1))
        version = match.group(2)
        if not _VERSION.fullmatch(version):
            raise LockError(f"Unsupported lock version: {version}")
        try:
            Version(version)
        except InvalidVersion as exc:
            raise LockError(f"Invalid locked version: {version}") from exc
        marker = match.group(3).strip() if match.group(3) else None
        if marker is not None:
            try:
                Marker(marker)
            except Exception as exc:  # packaging raises InvalidMarker
                raise LockError(f"Invalid locked marker for {name}: {marker}") from exc
            _reject_unsupported_marker(marker, f"locked {name}")
        hashes = []
        for field in entry.split(" --hash=")[1:]:
            digest = field.split(" ", 1)[0]
            if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
                raise LockError(f"Unsupported hash syntax: {digest[:40]}")
            hashes.append(digest.split(":", 1)[1])
        if len(set(hashes)) != len(hashes):
            raise LockError(f"Duplicate hash for {name}=={version}")
        pins.append(Pin(name=name, version=version, marker=marker, hashes=tuple(hashes)))
    identities = [(pin.name, pin.marker) for pin in pins]
    if len(set(identities)) != len(identities):
        raise LockError("Lock repeats a package with the same marker")
    return pins


_PLATFORM_FIELDS = {
    "linux": ("6.0.0-review", "#1 SMP review-linux"),
    "win32": ("10", "10.0.26100"),
    "darwin": ("24.0.0", "Darwin Kernel Version 24.0.0"),
}
_UNSUPPORTED_TARGET_FIELDS = frozenset({"platform_release", "platform_version"})


def _reject_unsupported_marker(marker: str, context: str) -> None:
    # pyproject/snapshot metadata can name arbitrary host builds; this audit cannot
    # express them, so fail closed instead of borrowing a host default.
    stripped = re.sub(r"(['\"]).*?\1", "", marker)
    if any(re.search(rf"\b{field}\b", stripped) for field in _UNSUPPORTED_TARGET_FIELDS):
        raise LockError(f"{context} uses a marker field this target audit cannot express: {marker}")


def _environments(config: dict[str, Any]) -> list[dict[str, str]]:
    policy = config["policy"]
    systems = {"linux": ("posix", "Linux"), "win32": ("nt", "Windows"), "darwin": ("posix", "Darwin")}
    required = set(default_environment())
    result = []
    for python in policy["python_versions"]:
        for platform in policy["platforms"]:
            os_name, system = systems[platform]
            release, version = _PLATFORM_FIELDS[platform]
            for machine in policy["machines"][platform]:
                environment = {
                    "implementation_name": "cpython",
                    "implementation_version": f"{python}.0",
                    "os_name": os_name,
                    "platform_machine": machine,
                    "platform_python_implementation": "CPython",
                    "platform_release": release,
                    "platform_system": system,
                    "platform_version": version,
                    "python_full_version": f"{python}.0",
                    "python_version": python,
                    "sys_platform": platform,
                    "extra": "",
                }
                missing = required - set(environment)
                if missing:
                    raise LockError(f"Declared marker environment is incomplete: {sorted(missing)}")
                result.append(environment)
    return result


def _active(pin: Pin, environment: dict[str, str]) -> bool:
    if pin.marker is None:
        return True
    try:
        return bool(Marker(pin.marker).evaluate(environment))
    except Exception as exc:  # packaging raises InvalidMarker/UndefinedEnvironmentName
        raise LockError(f"Unsupported marker {pin.marker!r}: {exc}") from exc


def _validate_manifest_sources(root: Path, profile: Profile) -> None:
    manifest, sources = _snapshot_manifest(root, profile)
    if manifest.get("format") != SNAPSHOT_FORMAT:
        raise LockError(f"{profile.name}: unsupported snapshot manifest format")
    for key, entry in sources.items():
        if not isinstance(entry, dict):
            raise LockError(f"{profile.name}: invalid source entry {key}")
        match = re.fullmatch(r"([a-z0-9][a-z0-9._-]*)==([^\s]+)", key)
        if match is None:
            raise LockError(f"{profile.name}: invalid source key {key}")
        name = canonicalize_name(match.group(1))
        version = match.group(2)
        _validate_source_url(str(entry.get("url")), name, version)
        path = root / profile.snapshots / f"{name}-{version}.source"
        try:
            data = path.read_bytes()
        except OSError as exc:
            raise LockError(f"{profile.name}: missing snapshot {path.relative_to(root)}") from exc
        if _digest(data) != entry.get("sha256"):
            raise LockError(f"{profile.name}: snapshot bytes do not match the manifest for {key}")
        try:
            metadata = json.loads(data)
        except (ValueError, UnicodeError) as exc:
            raise LockError(f"{profile.name}: invalid metadata snapshot for {key}") from exc
        info = metadata.get("info", {})
        if canonicalize_name(str(info.get("name", ""))) != name or info.get("version") != version:
            raise LockError(f"{profile.name}: snapshot identity does not match {key}")


def _validate_existing_update_state(root: Path, profile: Profile) -> None:
    """An update may only re-record a state it can first verify against the prior update."""
    manifest_present = (root / profile.snapshots / "manifest.json").exists()
    try:
        provenance = json.loads((root / PROVENANCE).read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError):
        provenance = None
    if not manifest_present:
        if provenance is not None and profile.name in provenance.get("profiles", {}):
            raise LockError(f"{profile.name}: provenance exists without a snapshot manifest")
        return
    _validate_manifest_sources(root, profile)
    if provenance is None:
        raise LockError(f"{profile.name}: snapshot manifest exists without recorded provenance")
    recorded = provenance.get("profiles", {}).get(profile.name)
    if not isinstance(recorded, dict):
        raise LockError(f"{profile.name}: snapshot manifest exists without a recorded update")
    actual = _digest((root / profile.snapshots / "manifest.json").read_bytes())
    if recorded.get("snapshots_sha256") != actual:
        raise LockError(
            f"{profile.name}: existing snapshot manifest differs from its recorded update; "
            "resolve the drift before updating"
        )


def _metadata(root: Path, profile: Profile, pin: Pin) -> dict[str, Any]:
    _manifest, sources = _snapshot_manifest(root, profile)
    key = f"{pin.name}=={pin.version}"
    entry = sources.get(key)
    if not isinstance(entry, dict):
        raise LockError(f"{profile.name}: no frozen metadata for {key}")
    _validate_source_url(str(entry.get("url")), pin.name, pin.version)
    path = root / profile.snapshots / f"{pin.name}-{pin.version}.source"
    try:
        data = path.read_bytes()
    except OSError as exc:
        raise LockError(f"{profile.name}: missing snapshot {path.relative_to(root)}") from exc
    if _digest(data) != entry.get("sha256"):
        raise LockError(f"{profile.name}: snapshot bytes do not match the manifest for {key}")
    try:
        metadata = json.loads(data)
    except (ValueError, UnicodeError) as exc:
        raise LockError(f"{profile.name}: invalid metadata snapshot for {key}") from exc
    info = metadata.get("info", {})
    if canonicalize_name(str(info.get("name", ""))) != pin.name or info.get("version") != pin.version:
        raise LockError(f"{profile.name}: snapshot identity does not match {key}")
    return metadata


def _snapshot_manifest(root: Path, profile: Profile) -> tuple[dict[str, Any], dict[str, Any]]:
    path = root / profile.snapshots / "manifest.json"
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError) as exc:
        raise LockError(f"Unable to read {path.relative_to(root)}: {exc}") from exc
    if not isinstance(manifest, dict) or manifest.get("format") != SNAPSHOT_FORMAT:
        raise LockError(f"Unsupported snapshot manifest format in {path.relative_to(root)}")
    sources = manifest.get("sources")
    if not isinstance(sources, dict):
        raise LockError(f"Snapshot manifest has no sources: {path.relative_to(root)}")
    return manifest, sources


def _wheel_hashes(metadata: dict[str, Any], key: str) -> set[str]:
    hashes = set()
    for item in metadata.get("urls", []):
        if not isinstance(item, dict):
            raise LockError(f"Invalid artifact metadata for {key}")
        if item.get("packagetype") != "bdist_wheel" or item.get("yanked"):
            continue
        digest = item.get("digests", {}).get("sha256")
        if isinstance(digest, str):
            hashes.add(digest)
    return hashes


def _all_hashes(metadata: dict[str, Any], key: str) -> set[str]:
    hashes = set()
    for item in metadata.get("urls", []):
        if not isinstance(item, dict):
            raise LockError(f"Invalid artifact metadata for {key}")
        digest = item.get("digests", {}).get("sha256")
        if isinstance(digest, str):
            hashes.add(digest)
    return hashes


def _verify_pin_artifacts(
    profile: Profile, pin: Pin, metadata: dict[str, Any], *, wheel_only: bool = True
) -> None:
    key = f"{pin.name}=={pin.version}"
    wheels = _wheel_hashes(metadata, key)
    everything = _all_hashes(metadata, key)
    for digest in pin.hashes:
        if digest not in everything:
            raise LockError(f"{profile.name}: hash for {key} is not published for that version")
        if wheel_only and digest not in wheels:
            raise LockError(f"{profile.name}: hash for {key} is not a wheel artifact")
    if not pin.hashes:
        raise LockError(f"{profile.name}: {key} has no installable hashes")


def _audit_closure(
    pins: list[Pin],
    metadata: dict[tuple[str, str], dict[str, Any]],
    environments: list[dict[str, str]],
    profile: str,
) -> None:
    for environment in environments:
        active: dict[str, Pin] = {}
        for pin in pins:
            if _active(pin, environment):
                if pin.name in active:
                    platform = f"{environment['sys_platform']} Python {environment['python_version']}"
                    raise LockError(f"{profile}: {pin.name} selects more than one version for {platform}")
                active[pin.name] = pin
        visited: set[tuple[str, str]] = set()
        queue = [(pin.name, "") for pin in active.values()]
        while queue:
            name, extra = queue.pop()
            if (name, extra) in visited:
                continue
            visited.add((name, extra))
            pin = active.get(name)
            if pin is None:
                raise LockError(f"{profile}: active dependency {name} is missing from the lock")
            metadata_entry = metadata[(pin.name, pin.version)]
            for raw in metadata_entry.get("info", {}).get("requires_dist") or []:
                try:
                    requirement = Requirement(raw)
                except InvalidRequirement as exc:
                    raise LockError(f"{profile}: invalid requirement metadata for {name}: {raw}") from exc
                if requirement.url is not None:
                    raise LockError(f"{profile}: direct URL dependencies are unsupported: {raw}")
                scoped = {**environment, "extra": extra}
                if requirement.marker is not None:
                    _reject_unsupported_marker(str(requirement.marker), f"{profile}: requirement {raw}")
                    if not requirement.marker.evaluate(scoped):
                        continue
                dependency = canonicalize_name(requirement.name)
                target = active.get(dependency)
                if target is None:
                    raise LockError(
                        f"{profile}: {name} requires {dependency}{requirement.specifier or ''} "
                        f"but the lock omits it"
                    )
                if requirement.specifier and not requirement.specifier.contains(
                    target.version, prereleases=True
                ):
                    raise LockError(
                        f"{profile}: locked {dependency}=={target.version} does not satisfy "
                        f"{requirement.specifier} from {name}"
                    )
                queue.extend((dependency, requested) for requested in sorted(requirement.extras))


def _environment_selections(
    pins: list[Pin], environments: list[dict[str, str]], *, profile: str
) -> list[dict[str, str]]:
    selections = []
    for environment in environments:
        selected: dict[str, str] = {}
        for pin in pins:
            if _active(pin, environment):
                if pin.name in selected:
                    cell = f"{environment['sys_platform']} Python {environment['python_version']}"
                    raise LockError(f"{profile}: {pin.name} selects more than one version for {cell}")
                selected[pin.name] = pin.version
        selections.append(selected)
    return selections


def _cross_profile_consistency(
    selections: dict[str, list[dict[str, str]]], environments: list[dict[str, str]]
) -> None:
    profiles = sorted(selections)
    for index, environment in enumerate(environments):
        involved: dict[str, dict[str, str]] = {}
        for profile in profiles:
            for name, version in selections[profile][index].items():
                involved.setdefault(name, {})[profile] = version
        for name in sorted(involved):
            versions = involved[name]
            if len(set(versions.values())) > 1:
                cell = f"{environment['sys_platform']} Python {environment['python_version']}"
                detail = ", ".join(f"{profile}={version}" for profile, version in sorted(versions.items()))
                raise LockError(f"Profiles select different versions of {name} for {cell}: {detail}")


def _diagnostics_body(root: Path, profiles: list[Profile]) -> dict[str, Any]:
    python = _requires_python(root, _read_config(root)["policy"])
    body: dict[str, Any] = {"format": 2, "python": ">=" + python, "profiles": {}}
    for profile in profiles:
        pins = _parse_lock(_read_profile_lock(root, profile))
        body["profiles"][profile.name] = {
            "requirements": [
                {"name": pin.name, "version": pin.version, "marker": pin.marker}
                for pin in sorted(pins, key=lambda item: (item.name, item.marker or ""))
            ]
        }
    body["recovery"] = {
        "core": "Install the hash-locked runtime requirements in a virtual environment",
        "search": "assets prepare",
    }
    return body


def _read_profile_lock(root: Path, profile: Profile) -> str:
    try:
        return (root / profile.lock).read_text(encoding="utf-8")
    except OSError as exc:
        raise LockError(f"Unable to read {profile.lock.as_posix()}: {exc}") from exc


def _lock_header(root: Path, profile: Profile, input_digest: str) -> bytes:
    config = _read_config(root)
    python = _requires_python(root, config["policy"])
    lines = [
        LOCK_HEADER,
        f"# Profile: {profile.name}; roots: {profile.roots.as_posix()}",
        f"# Policy: universal, python>={python}, wheel-only, hashes required.",
        f"# Inputs: policy={_policy_digest(root)} roots={input_digest}",
        "# Install with pip --require-hashes --only-binary=:all: -r this file.",
        "",
    ]
    return "\n".join(lines).encode("utf-8")


def _render(root: Path, profile: Profile, body: str, input_digest: str) -> bytes:
    if not body.endswith("\n"):
        body += "\n"
    return _lock_header(root, profile, input_digest) + body.encode("utf-8")


def _normalise_body(stdout: str) -> str:
    entries = []
    for raw in stdout.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        entries.append(raw.rstrip())
    return "\n".join(entries) + "\n"


def _run_update(root: Path, profile: Profile, uv: list[str], cache: Path) -> dict[str, Any]:
    config = _read_config(root)
    policy = config["policy"]
    python = _requires_python(root, policy)
    roots, _ = _root_inputs(root, profile)
    _validate_existing_update_state(root, profile)
    command = [
        *uv,
        "--no-config",
        "--cache-dir",
        str(cache),
        "pip",
        "compile",
        str(root / profile.roots),
        "--no-sources",
        "--universal",
        "--python-version",
        python,
        "--generate-hashes",
        "--only-binary",
        str(policy["only_binary"]),
        "--no-header",
        "--no-annotate",
        "--no-python-downloads",
        "--index-url",
        str(policy["index_url"]),
    ]
    completed = subprocess.run(
        command,
        capture_output=True,
        text=True,
        check=False,
        timeout=3600,
        env=_uv_environment(),
    )
    if completed.returncode != 0:
        raise LockError(completed.stderr.strip() or "uv resolution failed")
    body = _normalise_body(completed.stdout)
    pins = _parse_lock(body)
    locked = {pin.name: pin.version for pin in pins}
    for requirement in roots:
        name, version = requirement.split("==")
        if locked.get(name) != version:
            raise LockError(f"{profile.name}: resolver omitted root {name}=={version}")
    snapshots = _freeze_metadata(root, profile, pins)
    filtered = []
    for pin in pins:
        metadata = _metadata(root, profile, pin)
        wheels = _wheel_hashes(metadata, f"{pin.name}=={pin.version}")
        kept = tuple(digest for digest in pin.hashes if digest in wheels)
        if not kept:
            raise LockError(f"{profile.name}: {pin.name}=={pin.version} has no wheel artifact")
        filtered.append(Pin(name=pin.name, version=pin.version, marker=pin.marker, hashes=kept))
    input_digest = _input_digest(root, profile)
    lock = _render(root, profile, _render_body(filtered), input_digest)
    return {
        "lock": lock,
        "lock_sha256": _digest(lock),
        "roots_sha256": input_digest,
        "snapshots_sha256": snapshots,
        "pins": len(filtered),
    }


def _render_body(pins: list[Pin]) -> str:
    lines = []
    for pin in pins:
        head = f"{pin.name}=={pin.version}"
        if pin.marker is not None:
            head += f" ; {pin.marker}"
        lines.append(head + " \\")
        for index, digest in enumerate(pin.hashes):
            suffix = " \\" if index < len(pin.hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{suffix}")
    return "\n".join(lines) + "\n"


def _freeze_metadata(root: Path, profile: Profile, pins: list[Pin]) -> str:
    manifest, sources = _snapshot_manifest(root, profile)
    directory = root / profile.snapshots
    for pin in pins:
        key = f"{pin.name}=={pin.version}"
        path = directory / f"{pin.name}-{pin.version}.source"
        url = _source_url(pin.name, pin.version)
        frozen = sources.get(key)
        if path.exists() and isinstance(frozen, dict) and _digest(path.read_bytes()) == frozen.get("sha256"):
            _validate_frozen(path, pin, key)
            _validate_source_url(str(frozen.get("url")), pin.name, pin.version)
            try:
                _verify_pin_artifacts(profile, pin, json.loads(path.read_bytes()), wheel_only=False)
                continue
            except LockError:
                pass  # The frozen metadata predates resolved artifacts; refresh it.
        try:
            # The URL is built by _source_url against the approved official host.
            with urlopen(url, timeout=120) as response:  # noqa: S310
                data = response.read()
        except OSError as exc:
            raise LockError(f"Unable to retrieve {key} metadata: {exc}") from exc
        digest = _digest(data)
        path.write_bytes(data)
        _validate_frozen(path, pin, key)
        _verify_pin_artifacts(profile, pin, json.loads(data), wheel_only=False)
        sources[key] = {"url": url, "sha256": digest, "retrieved_at": datetime.now(UTC).isoformat()}
    directory.mkdir(parents=True, exist_ok=True)
    manifest["format"] = SNAPSHOT_FORMAT
    manifest["sources"] = dict(sorted(sources.items()))
    encoded = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    _atomic_write(directory / "manifest.json", encoded)
    return _digest(encoded)


def _validate_frozen(path: Path, pin: Pin, key: str) -> None:
    try:
        metadata = json.loads(path.read_bytes())
    except (OSError, ValueError, UnicodeError) as exc:
        raise LockError(f"Invalid metadata snapshot for {key}: {exc}") from exc
    info = metadata.get("info", {})
    if canonicalize_name(str(info.get("name", ""))) != pin.name or info.get("version") != pin.version:
        raise LockError(f"Snapshot identity does not match {key}")


def _write_diagnostics(root: Path, profiles: list[Profile]) -> str:
    path = root / _read_config(root)["diagnostics"]["path"]
    body = _diagnostics_body(root, profiles)
    encoded = (json.dumps(body, indent=2, sort_keys=True) + "\n").encode("utf-8")
    _atomic_write(path, encoded)
    return _digest(encoded)


def _write_provenance(root: Path, record: dict[str, Any]) -> None:
    encoded = (json.dumps(record, indent=2, sort_keys=True) + "\n").encode("utf-8")
    _atomic_write(root / PROVENANCE, encoded)


def update(root: Path = ROOT, cache: Path | None = None) -> dict[str, Any]:
    config = _read_config(root)
    profiles = _profiles(config)
    uv = _uv_command(root)
    temporary = None if cache is not None else tempfile.TemporaryDirectory(prefix="astrofairy-uv-")
    cache_path = cache if cache is not None else Path(temporary.name if temporary else ".")
    try:
        results = {}
        locks: dict[str, bytes] = {}
        for profile in profiles:
            updated = _run_update(root, profile, uv, cache_path)
            locks[profile.name] = updated.pop("lock")
            results[profile.name] = updated
        for profile in profiles:
            _atomic_write(root / profile.lock, locks[profile.name])
        diagnostics_sha = _write_diagnostics(root, profiles)
        record = {
            "format": 1,
            "generated_at": datetime.now(UTC).isoformat(),
            "tool": {
                "name": "uv",
                "version": _dev_tool_pin(
                    root, str(config["policy"]["uv_pin_name"]), str(config["policy"]["uv_pin_file"])
                ),
                "sha256": _uv_executable_digest(uv),
            },
            "policy": {
                "index_url": config["policy"]["index_url"],
                "only_binary": config["policy"]["only_binary"],
                "python": _requires_python(root, config["policy"]),
            },
            "profiles": results,
            "diagnostics_sha256": diagnostics_sha,
        }
        _write_provenance(root, record)
        return record
    finally:
        if temporary is not None:
            temporary.cleanup()


def check(root: Path = ROOT) -> dict[str, Any]:
    config = _read_config(root)
    profiles = _profiles(config)
    errors: list[str] = []
    try:
        provenance = json.loads((root / PROVENANCE).read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError) as exc:
        raise LockError(f"Unable to read lock provenance: {exc}") from exc
    if provenance.get("format") != 1:
        raise LockError("Unsupported lock provenance format")
    tool = provenance.get("tool", {})
    pinned = _dev_tool_pin(root, str(config["policy"]["uv_pin_name"]), str(config["policy"]["uv_pin_file"]))
    if tool.get("name") != "uv" or tool.get("version") != pinned:
        errors.append("The recorded resolver identity does not match the pinned development tool")
    tool_digest = tool.get("sha256")
    if not isinstance(tool_digest, str) or re.fullmatch(r"[0-9a-f]{64}", tool_digest) is None:
        errors.append("The recorded resolver executable digest is missing or malformed")
    environments = _environments(config)
    selections_by_profile: dict[str, list[dict[str, str]]] = {}
    metadata_by_profile: dict[str, dict[tuple[str, str], dict[str, Any]]] = {}
    for profile in profiles:
        try:
            text = _read_profile_lock(root, profile)
            pins = _parse_lock(text)
            header = text.split("\n\n", 1)[0]
            expected = _input_digest(root, profile)
            if f"roots={expected}" not in header:
                errors.append(f"{profile.name}: lock inputs do not match the current roots")
            if f"policy={_policy_digest(root)}" not in header:
                errors.append(f"{profile.name}: lock policy does not match the current policy")
            recorded = provenance.get("profiles", {}).get(profile.name)
            if not isinstance(recorded, dict):
                errors.append(f"{profile.name}: provenance has no lock record")
            else:
                if recorded.get("lock_sha256") != _digest((root / profile.lock).read_bytes()):
                    errors.append(f"{profile.name}: lock bytes differ from the recorded update")
                if recorded.get("roots_sha256") != expected:
                    errors.append(f"{profile.name}: provenance roots digest is stale")
                try:
                    actual_manifest = _digest((root / profile.snapshots / "manifest.json").read_bytes())
                except OSError as exc:
                    errors.append(f"{profile.name}: snapshot manifest is unreadable: {exc}")
                else:
                    if recorded.get("snapshots_sha256") != actual_manifest:
                        errors.append(
                            f"{profile.name}: snapshot manifest bytes differ from the recorded update"
                        )
            roots, _ = _root_inputs(root, profile)
            locked = {pin.name: pin for pin in pins if pin.marker is None}
            for requirement in roots:
                name, version = requirement.split("==")
                pin = locked.get(name)
                if pin is None or pin.version != version:
                    errors.append(f"{profile.name}: root {name}=={version} is not locked")
            try:
                _validate_manifest_sources(root, profile)
            except LockError as exc:
                errors.append(str(exc))
            metadata: dict[tuple[str, str], dict[str, Any]] = {}
            for pin in pins:
                try:
                    entry = _metadata(root, profile, pin)
                    _verify_pin_artifacts(profile, pin, entry)
                except LockError as exc:
                    errors.append(str(exc))
                    continue
                metadata[(pin.name, pin.version)] = entry
            if len(metadata) == len(pins):
                try:
                    _audit_closure(pins, metadata, environments, profile.name)
                except LockError as exc:
                    errors.append(str(exc))
            try:
                selections_by_profile[profile.name] = _environment_selections(
                    pins, environments, profile=profile.name
                )
            except LockError as exc:
                errors.append(str(exc))
            metadata_by_profile[profile.name] = metadata
        except LockError as exc:
            errors.append(f"{profile.name}: {exc}")
    if len(selections_by_profile) == len(profiles):
        try:
            _cross_profile_consistency(selections_by_profile, environments)
        except LockError as exc:
            errors.append(str(exc))
    try:
        diagnostics = _diagnostics_body(root, profiles)
        expected_bytes = (json.dumps(diagnostics, indent=2, sort_keys=True) + "\n").encode("utf-8")
        path = root / config["diagnostics"]["path"]
        if path.read_bytes() != expected_bytes:
            errors.append("Dependency diagnostics differ from the locked requirements")
        if provenance.get("diagnostics_sha256") != _digest(expected_bytes):
            errors.append("Dependency diagnostics differ from the recorded update")
    except (OSError, LockError) as exc:
        errors.append(f"Dependency diagnostics: {exc}")
    if errors:
        raise LockError("\n".join(errors))
    return {
        "profiles": {
            profile.name: len(_parse_lock(_read_profile_lock(root, profile))) for profile in profiles
        }
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="lock_dependencies")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--update", action="store_true", help="Resolve, refresh official metadata and rewrite locks"
    )
    mode.add_argument("--check", action="store_true", help="Offline consistency check of committed locks")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--cache-dir", type=Path)
    arguments = parser.parse_args(argv)
    try:
        if arguments.update:
            record = update(arguments.root, arguments.cache_dir)
            for name, item in record["profiles"].items():
                print(f"Updated {name}: {item['pins']} pins, lock {item['lock_sha256'][:12]}...")
            print("Dependency locks, official metadata and diagnostics updated")
            return 0
        summary = check(arguments.root)
        print(f"Dependency profiles agree with their official snapshots: {summary}")
        return 0
    except LockError as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
