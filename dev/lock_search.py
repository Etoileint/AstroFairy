from __future__ import annotations

import argparse
import hashlib
import json
import re
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "dev/search-requirements.in"
SNAPSHOTS = ROOT / "dev/search_snapshots"
MANIFEST = SNAPSHOTS / "manifest.json"
LOCK = ROOT / "skills/fairy/scripts/requirements-search.lock"


def _pins() -> dict[str, str]:
    result = {}
    for line in INPUT.read_text(encoding="utf-8").splitlines():
        value = line.strip()
        if not value or value.startswith("#"):
            continue
        requirement = Requirement(value)
        if (
            requirement.marker
            or requirement.extras
            or not re.fullmatch(r"==[A-Za-z0-9.]+", str(requirement.specifier))
        ):
            raise ValueError("Search requirements must be exact, unconditional pins")
        name = canonicalize_name(requirement.name)
        if name in result:
            raise ValueError("Duplicate search pin")
        result[name] = str(requirement.specifier)[2:]
    return result


def _fetch(name: str, version: str) -> bytes:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()


def _records(pins: dict[str, str], *, write: bool) -> dict[str, dict[str, str]]:
    SNAPSHOTS.mkdir(parents=True, exist_ok=True)
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.is_file() else {}
    for name, version in pins.items():
        path = SNAPSHOTS / f"{name}-{version}.source"
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        if write and (not path.is_file() or manifest.get(name, {}).get("url") != url):
            data = _fetch(name, version)
            path.write_bytes(data)
            manifest[name] = {
                "url": url,
                "sha256": hashlib.sha256(data).hexdigest(),
                "retrieved_at": datetime.now(UTC).isoformat(),
            }
        if not path.is_file() or name not in manifest:
            raise ValueError(f"Missing search metadata snapshot: {name}")
        data = path.read_bytes()
        if manifest[name]["url"] != url or hashlib.sha256(data).hexdigest() != manifest[name]["sha256"]:
            raise ValueError(f"Search metadata identity mismatch: {name}")
    if write:
        MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if set(manifest) != set(pins):
        raise ValueError("Search metadata manifest differs from the pinned closure")
    return manifest


def render(*, write: bool) -> str:
    pins = _pins()
    records = _records(pins, write=write)
    lines = [
        "# Generated by dev/lock_search.py from dev/search-requirements.in and official PyPI metadata.",
        "# Install with --require-hashes --only-binary=:all:.",
    ]
    for name, version in sorted(pins.items()):
        path = SNAPSHOTS / f"{name}-{version}.source"
        metadata = json.loads(path.read_text(encoding="utf-8"))
        if canonicalize_name(metadata["info"]["name"]) != name or metadata["info"]["version"] != version:
            raise ValueError(f"Search metadata identity mismatch: {name}")
        for value in metadata["info"]["requires_dist"] or []:
            dependency = Requirement(value)
            if dependency.marker is None or dependency.marker.evaluate({"extra": ""}):
                target = canonicalize_name(dependency.name)
                if target not in pins or not dependency.specifier.contains(pins[target], prereleases=True):
                    raise ValueError(f"Search lock omits or violates an active dependency: {target}")
        hashes = sorted(
            {
                item["digests"]["sha256"]
                for item in metadata["urls"]
                if item["packagetype"] == "bdist_wheel" and not item["yanked"]
            }
        )
        if not hashes:
            raise ValueError(f"Search release has no allowed wheel hashes: {name}")
        lines.append(f"{name}=={version} \\")
        lines.extend(
            f"    --hash=sha256:{value}" + (" \\" if index < len(hashes) - 1 else "")
            for index, value in enumerate(hashes)
        )
    del records
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    content = render(write=arguments.write)
    if arguments.write:
        LOCK.write_text(content, encoding="utf-8")
    elif not LOCK.is_file() or LOCK.read_text(encoding="utf-8") != content:
        print(f"Search dependency consumer drift: {LOCK.relative_to(ROOT)}")
        return 1
    print("Search pins, official snapshots and lock agree")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
