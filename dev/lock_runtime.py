from __future__ import annotations

import argparse
import hashlib
import json
import re
import tomllib
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def render(root: Path) -> dict[Path, str]:
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    pins = {}
    for value in project["project"]["dependencies"]:
        requirement = Requirement(value)
        if (
            requirement.marker
            or requirement.extras
            or not re.fullmatch(r"==[A-Za-z0-9.]+", str(requirement.specifier))
        ):
            raise ValueError("Runtime requirements must be exact, unconditional pins")
        name = canonicalize_name(requirement.name)
        if name in pins:
            raise ValueError("Duplicate runtime pin")
        pins[name] = str(requirement.specifier)[2:]
    snapshots = root / "dev/runtime_snapshots"
    records = json.loads((snapshots / "manifest.json").read_text(encoding="utf-8"))
    if set(records) != set(pins):
        raise ValueError("Runtime snapshots differ from the pinned closure")
    lines = [
        "# Generated by dev/lock_runtime.py from pyproject.toml and fixed official PyPI metadata.",
        "# Install with --require-hashes --only-binary=:all:.",
    ]
    for name, version in sorted(pins.items()):
        record = records[name]
        expected_url = f"https://pypi.org/pypi/{name}/{version}/json"
        path = snapshots / f"{name}-{version}.source"
        data = path.read_bytes()
        if record["url"] != expected_url or hashlib.sha256(data).hexdigest() != record["sha256"]:
            raise ValueError("Runtime release metadata identity mismatch")
        metadata = json.loads(data)
        if canonicalize_name(metadata["info"]["name"]) != name or metadata["info"]["version"] != version:
            raise ValueError("Runtime release metadata does not match its pin")
        for value in metadata["info"]["requires_dist"] or []:
            dependency = Requirement(value)
            if dependency.marker is None or dependency.marker.evaluate({"extra": ""}):
                target = canonicalize_name(dependency.name)
                if target not in pins or not dependency.specifier.contains(pins[target], prereleases=True):
                    raise ValueError("Runtime lock omits or violates an active dependency")
        hashes = sorted(
            {
                item["digests"]["sha256"]
                for item in metadata["urls"]
                if item["packagetype"] == "bdist_wheel" and not item["yanked"]
            }
        )
        if not hashes or any(not re.fullmatch(r"[a-f0-9]{64}", item) for item in hashes):
            raise ValueError("Runtime release has no valid allowed wheel hashes")
        lines.append(f"{name}=={version} \\")
        lines.extend(
            f"    --hash=sha256:{value}" + (" \\" if index < len(hashes) - 1 else "")
            for index, value in enumerate(hashes)
        )
    base = root / "skills/astrofairy/scripts"
    return {
        base / "requirements-runtime.lock": "\n".join(lines) + "\n",
        base / "astrofairy/_runtime_dependencies.json": json.dumps(pins, indent=2, sort_keys=True) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    for path, content in render(ROOT).items():
        if arguments.write:
            path.write_text(content, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"Runtime dependency consumer drift: {path.relative_to(ROOT)}")
            return 1
    print("Runtime pins, official snapshots and generated consumers agree")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
